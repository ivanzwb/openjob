/**
 * 输出格式片段：需要出代码的 prompt 共用。
 *
 * 渲染端只把 ``` 围栏里的内容按代码显示（等宽、缩进保留、横向滚动），
 * 裸代码会被当正文排版，缩进和换行全丢，长一点就完全没法读。模型默认
 * 未必加围栏，所以凡是可能出代码的 prompt 都要显式要求一次。
 */
export const CODE_FENCE_RULE = `代码格式（必须遵守）：
- 任何代码、命令行、配置片段都要写成 markdown 围栏代码块：\`\`\`语言名 开头、\`\`\` 结尾（如 \`\`\`python、\`\`\`java、\`\`\`bash）。
- 不要用纯缩进或裸文本贴代码，也不要省略语言名。
- 单个函数名、变量名、字段名等行内代码用反引号包裹。`;

/**
 * completeJson 会追加「不要 markdown 代码块」——那说的是别把整个 JSON 响应
 * 包进围栏。这里要的围栏在 markdown 字段的字符串值内部，两者不是一回事，
 * 不点破模型会二选一，通常选择整段不加围栏。
 */
export const CODE_FENCE_RULE_IN_JSON = `${CODE_FENCE_RULE}
- 围栏写在 markdown 字段的字符串值里面（换行照常转义成 \\n），不要把整个 JSON 响应包进围栏。`;
