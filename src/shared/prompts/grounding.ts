/**
 * 简历与 JD 的角色分工规则。
 *
 * 上下文里有两类东西长得很像但性质相反：简历写的是候选人真实做过的事，
 * JD / 公司技术栈 / 面经写的是他还没做过、正要去争取的岗位要求。模型默认
 * 把两者都当成「关于这个人的资料」，于是拿岗位职责当项目经历编故事。用户
 * 照着背上考场，面试官追问两句就穿帮——这比答不上来更糟。
 *
 * 规则分两种，因为出题和代答对 JD 的正当用法根本不同：
 * - 代答类（参考答案、举例、改进话术）说的是「候选人做过什么」，JD 一点都不能掺。
 * - 出题类反过来，考 JD 里候选人还没做过的缺口正是面试的一部分，只是题干
 *   不能预设他做过。两者用同一条规则的话，要么答案继续编，要么出题被限死在
 *   简历范围内，考不出缺口。
 */

/** 会产出「候选人自述内容」的 prompt 用这条：参考答案、举例、改进话术 */
export const RESUME_GROUNDING_RULE = `## 事实来源（必须遵守）
- 候选人做过的事只有一个来源：上下文里的简历经历 / 简历项目 / 简历技能。
- 岗位 JD、公司技术栈、公司情报、面经真题描述的是目标岗位的要求，不是候选人的经历，任何情况下都不得当成他做过的事写进答案。
- JD 只有两种正当用法：判断哪些内容对这个岗位更重要，以及说明候选人为什么匹配这个岗位。
- 简历里没有的公司、项目、职责、技术栈、数据指标一律不要编。简历没写清楚的地方宁可说得笼统，也不要补成具体故事。
- 简历为空、或与本题确实无关时，用不含具体细节的通用表述，并明确标注「可换成你简历里的 XXX 经历」——不要用 JD 里的内容顶替这个位置。`;

/** 只出题、不代答的 prompt 用这条 */
export const QUESTION_GROUNDING_RULE = `## 出题的事实来源（必须遵守）
- 可以考 JD 要求里候选人还没做过的部分：考察缺口本来就是面试的一部分。
- 但题干不得预设候选人做过某件事。除非那件事写在简历里，否则不要出现「你在 X 项目中……」这种问法。
- 需要基于个人经历提问时，只能引用简历里真实存在的经历。简历里没有可用经历，就把题目改成不依赖个人经历的形式（如「如果让你设计……」）。`;

/**
 * 评分改进稿的取材约束。
 *
 * 评分场景比出题和代答都更容易出问题：模型为了让改进稿显得完整，会顺手把 JD
 * 里的技术栈补进候选人的答案，等于替他编了一段没发生过的经历。
 */
export const SCORE_GROUNDING_RULE = `## 改进稿的事实来源（必须遵守）
- 改进稿是把候选人这次的回答改得更好，不是换一个更理想的候选人来答。
- 只能用候选人回答里已有的事实，以及上下文简历里的经历；不要拿 JD、公司技术栈里的内容替他补经历或补指标。
- 他答漏的地方，在反馈里指出「这里可以补上你简历中的 XXX」，而不是在改进稿里直接替他编一个。`;

/**
 * 走 CandidateEvidence 的个人事实约束。
 *
 * 和 RESUME_GROUNDING_RULE 是同一条线的两种投影：简历版说的是「只能从简历取材」，
 * 这条说的是「只能从已确认的证据条目取材，并且要标出取的是哪一条」。组合器把
 * 可用证据连同 id 一起注入，模型才有东西可标；标不出 id 的个人事实在提交前会被
 * 事实校验拦掉（fail closed），所以这里必须要求逐句标注，而不是「尽量标注」。
 */
export const EVIDENCE_GROUNDING_RULE = `## 候选人证据（必须遵守）
- 「候选人证据」小节里的每一条都是已确认事实，带一个 evidence id。
- 涉及候选人个人经历的句子只能建立在这些条目上，并在句末标注 [evidence:<id>]。
- 小节里没有的公司、项目、职责、技术栈、数据指标一律不要写，也不要用 JD、公司信息或通用案例顶替。
- 没有可用条目时直接说明缺少证据，不要给出任何以候选人口吻叙述的经历。`;

